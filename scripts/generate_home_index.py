def doc_label(doc) -> str:
    """Short link label: subcategory (falling back to category) + version."""
    base = doc.subcategory or doc.category or doc.title
    # The card is already titled with the product name — drop the
    # redundant prefix from title-derived labels ("ER805 认证证书" -> "认证证书").
    if base == doc.title and base.startswith(doc.product + " "):
        base = base[len(doc.product) + 1:]
    version = parse_version(doc.link)
    return f"{base} V{version}" if version else base


def build_cards(lang: str) -> str:
    docs = collect(lang, base_url=None)
    visible = [
        d for d in docs
        if d.category.lower() not in EXCLUDED_CATEGORIES
        and "/images/" not in d.link
    ]

    by_product: dict[str, list] = {}
    for d in visible:
        by_product.setdefault(d.product, []).append(d)

    cards: list[str] = []
    # Secondary key breaks the tie between case-variant product dirs
    # (e.g. "MO 68A" vs "Mo 68A") identically on all platforms.
    for product in sorted(by_product, key=lambda p: (p.lower(), p)):
        group = sorted(by_product[product], key=lambda d: (d.category, d.subcategory, d.link))
        labels = [doc_label(d) for d in group]
        items = []
        for d, raw_label in zip(group, labels):
            href = quote(d.link[: -len(".md")] + ".html", safe="/")
            # Duplicate labels within one product (e.g. two FlexAPI docs)
            # are indistinguishable — fall back to the document title.
            label = html.escape(d.title if labels.count(raw_label) > 1 else raw_label)
            title_attr = html.escape(d.title, quote=True)
            items.append(
                f'        <li><a href="{href}" title="{title_attr}">{label}</a></li>'
            )
        cards.append(
            '    <div class="pm-card">\n'
            '      <div class="pm-card__body">\n'
            f'        <div class="pm-card__title">{html.escape(product)}</div>\n'
            '        <ul class="pm-card__links">\n'
            + "\n".join(items) + "\n"
            "        </ul>\n"
            "      </div>\n"
            "    </div>"
        )
    return "\n".join(cards)


