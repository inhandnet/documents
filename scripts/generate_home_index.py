"""Generate the site homepage (docs/zh/index.md, docs/en/index.md).

Replaces the old hand-written demo homepage with a real product directory:
one card per product, each card listing links to the documents that actually
exist in the built site.

Design notes
------------
- Standard library only (same constraint as generate_llms_txt.py).
- Reuses generate_llms_txt.collect() so homepage and llms.txt can never
  disagree about what documents exist.
- Skips categories excluded from the mkdocs build (Datasheets,
  Certification Documents, Drawings) and stray md under images/ —
  linking to them would produce 404s on the published site.
- Links point at the built *.html twins (use_directory_urls: false) and
  are percent-encoded so they survive spaces / CJK in paths.
- Output is deterministic: same content -> byte-identical file.

Usage
-----
    python scripts/generate_home_index.py            # writes both langs
    python scripts/generate_home_index.py --lang zh
    python scripts/generate_home_index.py --check    # non-zero exit if stale
"""

