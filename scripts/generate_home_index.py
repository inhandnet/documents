def render(lang: str) -> str:
    meta = PAGE_META[lang]
    return (PAGE_TEMPLATE
            .replace("@@FRONT_TITLE@@", meta["frontmatter_title"])
            .replace("@@MARKER@@", GENERATED_MARKER)
            .replace("@@TITLE@@", html.escape(meta["title"]))
            .replace("@@SUBTITLE@@", html.escape(meta["subtitle"]))
            .replace("@@ARIA@@", meta["search_aria"])
            .replace("@@PLACEHOLDER@@", meta["search_placeholder"])
            .replace("@@NO_RESULTS@@", meta["no_results"])
            .replace("@@RESULTS_SUFFIX@@", meta["results_suffix"])
            .replace("@@CARDS@@", build_cards(lang)))


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate homepage index.md files.")
    ap.add_argument("--lang", choices=["en", "zh"], action="append",
                    help="Limit to given language(s); default both.")
    ap.add_argument("--check", action="store_true",
                    help="Do not write; exit non-zero if any homepage is stale.")
    args = ap.parse_args()

    langs = args.lang or ["en", "zh"]
    stale = False
    for lang in langs:
        lang_root = DOCS_DIR / lang
        if not lang_root.is_dir():
            print(f"skip {lang}: {lang_root} not found", file=sys.stderr)
            continue
        content = render(lang)
        out = lang_root / "index.md"
        if args.check:
            existing = out.read_text(encoding="utf-8") if out.exists() else ""
            if existing != content:
                stale = True
                print(f"STALE: {out.relative_to(REPO_ROOT).as_posix()}")
            continue
        # newline="\n": identical output on Windows and CI (Linux)
        out.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(REPO_ROOT).as_posix()}")

    if args.check and stale:
        print("homepage is out of date; run scripts/generate_home_index.py",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
